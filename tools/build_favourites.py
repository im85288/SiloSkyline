#!/usr/bin/env python3
"""Write xml/MyFavourites.xml: Kodi's Favourites in Skyline's style.

    python3 tools/build_favourites.py

It was Estuary's, with its five views and side menu. A favourite can be
anything: a film, a folder, an add-on, a script, each with a picture of its own
shape or only one of Kodi's icons. So: a grid of dark 16:9 tiles, as the add-on
video grid's cards, each picture whole on its tile and a small icon centred, with
the name beneath. Kodi's own menu (the context key) moves, renames and removes
them. With none, Kodi still lists its ".." row, which keeps focus but isn't drawn.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_home import BACKGROUND, ROOT, SAFE_X, TEXT, TITLE_DIM, focus_sheen, focus_zoom  # noqa: E402
from build_browse import VIDEO_GAP, VIDEO_H, VIDEO_W  # noqa: E402

LIST_ID = 50
TOP = 200
ITEM_W, ITEM_H = VIDEO_W + VIDEO_GAP, VIDEO_H + 12 + 34 + 34
MASK = 'silo/card_landscape_mask.png'
TILE = 'FF1C1F24'
ICON = 96
A_KODI_ICON = 'String.StartsWith(ListItem.Icon,Default)'


def card(focused):
    lit = 'Control.HasFocus(%d)' % LIST_ID
    scroll = '\n                    <scroll>true</scroll>\n                    <scrollspeed>50</scrollspeed>' if focused else ''
    return '''
                <control type="group">
                    <width>%(w2)d</width><height>%(h2)d</height>%(zoom)s
                    <visible>!ListItem.IsParentFolder</visible>
                    <control type="image">
                        <left>6</left><top>6</top><width>%(w)d</width><height>%(h)d</height>
                        <texture diffuse="%(mask)s" colordiffuse="%(tile)s">colors/white.png</texture>
                    </control>
                    <control type="image">
                        <left>6</left><top>6</top><width>%(w)d</width><height>%(h)d</height>
                        <aspectratio>keep</aspectratio>
                        <texture background="true" diffuse="%(mask)s">$INFO[ListItem.Icon]</texture>
                        <visible>!%(glyph)s</visible>
                    </control>
                    <control type="image">
                        <left>%(ix)d</left><top>%(iy)d</top><width>%(icon)d</width><height>%(icon)d</height>
                        <aspectratio>keep</aspectratio>
                        <texture>$INFO[ListItem.Icon]</texture>
                        <visible>%(glyph)s</visible>
                    </control>%(sheen)s
                </control>
                <control type="label">
                    <left>6</left><top>%(ty)d</top><width>%(w)d</width><height>34</height>
                    <aligny>center</aligny>
                    <font>silo_card_title</font>
                    <textcolor>%(colour)s</textcolor>
                    <label>$INFO[ListItem.Label]</label>%(scroll)s
                    <visible>!ListItem.IsParentFolder</visible>
                </control>''' % {
        'w': VIDEO_W, 'h': VIDEO_H, 'w2': VIDEO_W + 12, 'h2': VIDEO_H + 12, 'mask': MASK, 'tile': TILE, 'glyph': A_KODI_ICON,
        'zoom': focus_zoom(lit) if focused else '', 'ix': 6 + (VIDEO_W - ICON) // 2, 'iy': 6 + (VIDEO_H - ICON) // 2,
        'icon': ICON, 'ty': VIDEO_H + 18, 'colour': TEXT if focused else TITLE_DIM, 'scroll': scroll,
        'sheen': focus_sheen(VIDEO_W, VIDEO_H, MASK, 'silo/card_landscape_rim.png', lit, 20) if focused else ''}


def build():
    return '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build_favourites.py: edit that, not this. -->
<window>
    <defaultcontrol always="true">%(list)d</defaultcontrol>
    <backgroundcolor>%(background)s</backgroundcolor>
    <views>%(list)d</views>
    <controls>
        <control type="image">
            <left>0</left><top>0</top><width>1920</width><height>1080</height>
            <texture colordiffuse="%(background)s">colors/white.png</texture>
        </control>
        <include content="SiloFrame">
            <param name="title">$LOCALIZE[1036]</param>
            <param name="sub">$INFO[Container.NumItems,, items]</param>
        </include>
        <control type="panel" id="%(list)d">
            <left>%(x)d</left><top>%(top)d</top><width>%(w)d</width><height>%(h)d</height>
            <orientation>vertical</orientation>
            <scrolltime tween="cubic" easing="out">280</scrolltime>
            <onleft>noop</onleft><onright>noop</onright>
            <itemlayout width="%(iw)d" height="%(ih)d">%(normal)s
            </itemlayout>
            <focusedlayout width="%(iw)d" height="%(ih)d">%(focus)s
            </focusedlayout>
        </control>
        <control type="group">
            <left>%(ex)d</left><top>%(top)d</top>
            <visible>Integer.IsEqual(Container.NumItems,0) + !Container.IsUpdating</visible>
            <control type="label">
                <width>1400</width><height>60</height>
                <font>silo_meta</font>
                <textcolor>%(text)s</textcolor>
                <label>No favourites yet</label>
            </control>
            <control type="label">
                <top>54</top><width>1400</width><height>44</height>
                <font>silo_detail</font>
                <textcolor>99EDEDED</textcolor>
                <label>Hold OK on anything in a list, then choose Add to favourites.</label>
            </control>
        </control>
    </controls>
</window>
''' % {'list': LIST_ID, 'background': BACKGROUND, 'x': SAFE_X - 6, 'ex': SAFE_X, 'top': TOP, 'w': 1920 - 2 * (SAFE_X - 6),
       'h': 1080 - TOP, 'iw': ITEM_W, 'ih': ITEM_H, 'normal': card(False), 'focus': card(True), 'text': TEXT}


if __name__ == '__main__':
    with open(os.path.join(ROOT, 'xml', 'MyFavourites.xml'), 'w', encoding='utf-8') as handle:
        handle.write(build())
    print('Wrote xml/MyFavourites.xml')
