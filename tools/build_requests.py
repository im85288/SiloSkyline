#!/usr/bin/env python3
"""Generate Skyline's request browse page (xml/Custom_1197_SiloRequestBrowse.xml):

    python3 tools/build_requests.py

Silo's Requests page opens it for a studio's, network's or genre's titles
(its tiles): a grid of Silo's request posters, with its tags, from
SiloKodiConnect (mode=requests, row in
Window(Home).Property(silo.rbrowse.row), its title in silo.rbrowse.title).
A genre has Movies and Series, as Silo's genre pages.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_home import GRID_POSTER, ROOT, TEXT, TAB_DIM, REQUEST_BROWSE, GRID_BACKDROP  # noqa: E402

GRID = 50
MOVIES, SERIES = 70, 71
ROW = 'Window(Home).Property(silo.rbrowse.row)'
MEDIA = 'Window(Home).Property(silo.rbrowse.media)'
GENRE = 'String.StartsWith(%s,browse:genre:)' % ROW
PATH = ('plugin://plugin.video.silokodiconnect/?mode=requests&amp;row=$INFO[%s]$INFO[%s,:,]' % (ROW, MEDIA))


def pill(control_id, label, media, left, right):
    """Movies or Series on a genre's page: the shown one lit."""
    shown = ('String.IsEqual(%s,series)' % MEDIA) if media == 'series' else ('!String.IsEqual(%s,series)' % MEDIA)
    return '''
            <control type="button" id="%(id)d">
                <width>auto</width><height>48</height>
                <label>%(label)s</label>
                <font>silo_meta</font>
                <textoffsetx>22</textoffsetx>
                <align>center</align><aligny>center</aligny>
                <textcolor>$VAR[SiloRequestPill%(name)s]</textcolor>
                <focusedcolor>FF000000</focusedcolor>
                <texturefocus border="24" colordiffuse="%(text)s">silo/pill.png</texturefocus>
                <texturenofocus border="24" colordiffuse="$VAR[SiloRequestPillFill%(name)s]">silo/pill.png</texturenofocus>
                <onleft>%(left)s</onleft><onright>%(right)s</onright>
                <ondown>%(grid)d</ondown>
                <onclick>%(click)s</onclick>
            </control>''' % {'id': control_id, 'label': label, 'name': label, 'text': TEXT, 'left': left, 'right': right,
                             'grid': GRID, 'shown': shown,
                             'click': 'SetProperty(silo.rbrowse.media,series,home)' if media == 'series'
                             else 'ClearProperty(silo.rbrowse.media,home)'}


CLICKS = ('''
            <!-- A title Silo can request: its request page; one in the library: its info page. -->
            <onclick condition="!String.IsEmpty(ListItem.Property(silo.request.tmdb))">RunPlugin(plugin://plugin.video.silokodiconnect/?mode=request_info&amp;type=$INFO[ListItem.Property(silo.request.type)]&amp;tmdb=$INFO[ListItem.Property(silo.request.tmdb)])</onclick>
            <onclick condition="String.IsEmpty(ListItem.Property(silo.request.tmdb))">RunPlugin(plugin://plugin.video.silokodiconnect/?mode=info&amp;type=$INFO[ListItem.DBType]&amp;dbid=$INFO[ListItem.DBID])</onclick>''')


def cards(control_id, width, height):
    return '''
            <itemlayout width="%(w)d" height="%(h)d">
                <include>SiloCardGridPoster</include>
            </itemlayout>
            <focusedlayout width="%(w)d" height="%(h)d">
                <include content="SiloCardFocusedGridPoster"><param name="id" value="%(id)d" /></include>
            </focusedlayout>''' % {'w': width, 'h': height, 'id': control_id}


def variables():
    """The genre pills' colours: the media type showing lit."""
    out = ''
    for label, shown in (('Movies', '!String.IsEqual(%s,series)' % MEDIA), ('Series', 'String.IsEqual(%s,series)' % MEDIA)):
        out += ('    <variable name="SiloRequestPill%s">\n        <value condition="%s">%s</value>\n'
                '        <value>%s</value>\n    </variable>\n' % (label, shown, TEXT, TAB_DIM))
        out += ('    <variable name="SiloRequestPillFill%s">\n        <value condition="%s">33FFFFFF</value>\n'
                '        <value>12FFFFFF</value>\n    </variable>\n' % (label, shown))
    return out


def build():
    # A row's gap as wide as a column's, so a focused card's caption clears the next row.
    item = GRID_POSTER['width'] + GRID_POSTER['gap'], GRID_POSTER['height'] + 12 + 76 + GRID_POSTER['gap']
    return '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build_requests.py: edit that, not this. -->
<window id="%(window)d">
    <defaultcontrol always="true">%(grid)d</defaultcontrol>
    <!-- A genre opens on its movies; leaving forgets the choice. -->
    <onunload>ClearProperty(silo.rbrowse.media,home)</onunload>
    <backgroundcolor>SkylineBackground</backgroundcolor>
    <controls>
        <include>SiloPage</include>
        <!-- The focused title's artwork, faint behind the grid. -->
        <control type="image">
            <left>576</left><top>0</top><width>1344</width><height>756</height>
            <aspectratio>stretch</aspectratio>
            <fadetime>240</fadetime>
            <texture background="true" colordiffuse="%(backdrop)s" diffuse="silo/hero_mask.png">$INFO[Container(%(grid)d).ListItem.Art(fanart)]</texture>
        </control>
        <include content="SiloFrame">
            <param name="title">$INFO[Window(Home).Property(silo.rbrowse.title)]</param>
            <param name="sub">$INFO[Container(%(grid)d).NumItems,, titles]</param>
        </include>
        <control type="grouplist">
            <left>82</left><top>176</top><width>800</width><height>48</height>
            <orientation>horizontal</orientation>
            <itemgap>12</itemgap>
            <visible>%(genre)s</visible>%(pills)s
        </control>
        <control type="panel" id="%(grid)d">
            <left>76</left><top>252</top>
            <width>1780</width><height>828</height>
            <orientation>vertical</orientation>
            <onup condition="%(genre)s">%(movies)d</onup>
            <onleft>noop</onleft><onright>noop</onright>
            <scrolltime tween="cubic" easing="out">280</scrolltime>%(clicks)s%(cards)s
            <content target="videos">%(path)s</content>
        </control>
    </controls>
</window>
''' % {'backdrop': GRID_BACKDROP, 'window': REQUEST_BROWSE, 'grid': GRID, 'genre': GENRE, 'movies': MOVIES, 'iw': item[0], 'ih': item[1],
       'path': PATH, 'clicks': CLICKS, 'cards': cards(GRID, item[0], item[1]),
       'pills': pill(MOVIES, 'Movies', 'movie', 'noop', SERIES) + pill(SERIES, 'Series', 'series', MOVIES, 'noop')}


START, END = '    <!-- Silo Skyline request browse (tools/build_requests.py) -->\n', '    <!-- end Silo Skyline request browse -->\n'


def add_variables():
    path = os.path.join(ROOT, 'xml', 'Variables.xml')
    text = open(path, encoding='utf-8').read()
    if START in text:
        text = text[:text.index(START)] + text[text.index(END) + len(END):]
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write(text.replace('</includes>', START + variables() + END + '</includes>'))


if __name__ == '__main__':
    with open(os.path.join(ROOT, 'xml', 'Custom_%d_SiloRequestBrowse.xml' % REQUEST_BROWSE), 'w', encoding='utf-8') as handle:
        handle.write(build())
    add_variables()
    print('Wrote xml/Custom_%d_SiloRequestBrowse.xml' % REQUEST_BROWSE)
