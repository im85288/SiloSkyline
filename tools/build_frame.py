def tile(focused):
    lit = 'Control.HasFocus(9000)'
    def body(icon_colour, text_colour):
        return '''
				<control type="image">
					<left>%(il)d</left><top>42</top><width>96</width><height>96</height>
					<aspectratio>keep</aspectratio>
					<texture colordiffuse="%(ic)s">$INFO[ListItem.Icon]</texture>
				</control>
				<control type="label">
					<left>16</left><top>148</top><width>%(lw)d</width><height>44</height>
					<align>center</align><aligny>center</aligny>
					<font>silo_meta</font>
					<textcolor>%(tc)s</textcolor>
					<label>$INFO[ListItem.Label]</label>
				</control>''' % {'il': (TILE_W - 12 - 96) // 2, 'ic': icon_colour, 'tc': text_colour,
                                 'lw': TILE_W - 12 - 32}
    card = '''
				<control type="image">
					<width>%(w)d</width><height>%(h)d</height>
					<texture border="20" colordiffuse="%(c)s">silo/card_landscape_mask.png</texture>%(v)s
				</control>'''
    if not focused:
        return card % {'w': TILE_W - 12, 'h': TILE_H - 12, 'c': '14FFFFFF', 'v': ''} + body('D9EDEDED', 'D9EDEDED')
    shown = '\n					<visible>%s</visible>' % lit
    hidden = '\n					<visible>!%s</visible>' % lit
    return (card % {'w': TILE_W - 12, 'h': TILE_H - 12, 'c': TEXT, 'v': shown}
            + body('FF000000', 'FF000000').replace('</control>', '%s\n				</control>' % shown)
            + card % {'w': TILE_W - 12, 'h': TILE_H - 12, 'c': '14FFFFFF', 'v': hidden}
            + body('D9EDEDED', 'D9EDEDED').replace('</control>', '%s\n				</control>' % hidden))


