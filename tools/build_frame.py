def main():
    with open(xml_path('Includes_SiloFrame.xml'), 'w', encoding='utf-8') as handle:
        handle.write(includes())
    path = xml_path('Includes.xml')
    text = open(path, encoding='utf-8').read()
    if '<include file="Includes_SiloFrame.xml" />' not in text:
        text = text.replace('\t<include file="Includes_SiloCards.xml" />',
                            '\t<include file="Includes_SiloCards.xml" />\n\t<include file="Includes_SiloFrame.xml" />', 1)
    text = replace_include(text, 'TopBar', top_bar())
    # The title line's font: Silo's wordmark size.
    text = re.sub(r'(<include name="BreadcrumbsLabel">\s*)<font>[^<]*</font>(\s*)<shadowcolor>[^<]*</shadowcolor>(\s*)<top>7</top>(\s*)<height>100</height>',
                  r'\1<font>silo_wordmark</font>\2<textcolor>FFEDEDED</textcolor>\3<top>0</top>\4<height>58</height>', text)
    open(path, 'w', encoding='utf-8').write(text)
    path = xml_path('Includes_Buttons.xml')
    text = open(path, encoding='utf-8').read()
    open(path, 'w', encoding='utf-8').write(replace_include(text, 'DefaultSettingButton', setting_button()))
    # Skin settings: Estuary's window (tools/source) with the frame's edits.
    source = os.path.join(ROOT, 'tools', 'source', 'SkinSettings.xml')
    with open(xml_path('SkinSettings.xml'), 'w', encoding='utf-8') as handle:
        handle.write(skin_settings(open(source, encoding='utf-8').read()))
    # Estuary's list views (add-ons, programs, favourites...): white-pill rows.
    for name, list_id in (('View_50_List', '$PARAM[list_id]'), ('View_55_WideList', '55')):
        source = os.path.join(ROOT, 'tools', 'source', name + '.xml')
        with open(xml_path(name + '.xml'), 'w', encoding='utf-8') as handle:
            handle.write(white_pill_rows(open(source, encoding='utf-8').read(), list_id))
    # Estuary's side panel behind lists: Silo's page shows instead.
    path = xml_path('Includes.xml')
    text = open(path, encoding='utf-8').read()
    text = text.replace('<texture flipx="$PARAM[flipx]" colordiffuse="EDFFFFFF">lists/panel.png</texture>\n\t\t\t\t<bordertexture border="21" infill="false">overlays/shadow.png</bordertexture>\n\t\t\t\t<bordersize>20</bordersize>',
                        '<texture colordiffuse="00FFFFFF">colors/white.png</texture>')
    open(path, 'w', encoding='utf-8').write(text)
    with open(xml_path('SettingsSystemInfo.xml'), 'w', encoding='utf-8') as handle:
        handle.write(system_info_window())
    with open(xml_path('LoginScreen.xml'), 'w', encoding='utf-8') as handle:
        handle.write(login_screen_window())
    with open(xml_path('SettingsProfile.xml'), 'w', encoding='utf-8') as handle:
        handle.write(profiles_window())
    with open(xml_path('FileManager.xml'), 'w', encoding='utf-8') as handle:
        handle.write(file_manager_window())
    with open(xml_path('Settings.xml'), 'w', encoding='utf-8') as handle:
        handle.write(settings_window())
    with open(xml_path('SettingsCategory.xml'), 'w', encoding='utf-8') as handle:
        handle.write(settings_category_window())
    print('Wrote xml/Includes_SiloFrame.xml, Settings.xml, SettingsCategory.xml; the frame in Includes.xml\'s '
          'TopBar; setting rows in Includes_Buttons.xml')


if __name__ == '__main__':
    main()
