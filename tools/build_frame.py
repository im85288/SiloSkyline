FOCUS_IMAGE = re.compile(r'<texture border="14" colordiffuse="2EFFFFFF">silo/card_landscape_mask.png</texture>')


def white_pill_rows(text, list_id):
    """Estuary's list views (from tools/source) with the frame's focus: in
    every focused layout the bar becomes the white pill (faded while the list
    doesn't have focus) and its text and icons turn black."""
    def layout(match):
        block = match.group(0)
        block = FOCUS_IMAGE.sub('<texture border="30" colordiffuse="%s">%s</texture>' % (TEXT, FOCUS_ROW), block)
        # The pill always shows (black text needs it), dimmed off focus.
        block = re.sub(r'\s*<visible>Control\.HasFocus\(%s\)</visible>' % re.escape(list_id), '', block, count=1)
        block = block.replace('<texture border="30" colordiffuse="%s">%s</texture>' % (TEXT, FOCUS_ROW),
                              '<texture border="30" colordiffuse="%s">%s</texture>\n\t\t\t\t\t\t<animation effect="fade" start="100" end="40" time="100" condition="!Control.HasFocus(%s)">Conditional</animation>'
                              % (TEXT, FOCUS_ROW, list_id), 1)
        def label(m):
            control = m.group(0)
            control = re.sub(r'\s*<shadowcolor>[^<]*</shadowcolor>', '', control)
            control = re.sub(r'\s*<textcolor>[^<]*</textcolor>', '', control)
            return control.replace('</control>', '\t<textcolor>FF000000</textcolor>\n\t\t\t\t\t</control>', 1)
        block = re.sub(r'<control type="(?:label|textbox)">.*?</control>', label, block, flags=re.S)
        # Icons black too; a second copy coloured for "unfocused" goes.
        block = re.sub(r'<texture( [^>]*)?>(\$VAR\[ListWatchedIconVar\]|\$INFO\[ListItem\.Icon\]|\$VAR\[[A-Za-z]*Icon[A-Za-z]*\])</texture>',
                       r'<texture colordiffuse="FF000000">\2</texture>', block)
        return block
    return re.sub(r'<focusedlayout[^>]*>.*?</focusedlayout>', layout, text, flags=re.S)


